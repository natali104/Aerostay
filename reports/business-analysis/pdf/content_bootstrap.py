def n(v):
    return float(v)


def eur(v, k=False):
    v = n(v)
    sign = "−" if v < 0 else ""
    if k and abs(v) >= 1_000_000:
        return f"{sign}€{abs(v) / 1e6:.2f}".replace(".", ",") + NB + "млн"
    if k:
        return f"{sign}€{abs(v) / 1000:,.0f}".replace(",", NB) + NB + "хил."
    return f"{sign}€{abs(v):,.0f}".replace(",", NB)


def num(v):
    v = n(v)
    return ("−" if v < 0 else "") + f"{abs(v):,.0f}".replace(",", NB)


